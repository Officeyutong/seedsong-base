//! Bootstrap local regression fixtures, never claim these as independent spec vectors.
use seedsong_core::{dna::Dna, music::Song, rng::Stream};
fn main() {
    let mut rng = Stream::new("sng/local-regression", &[]);
    let vectors: Vec<_> = (0..100)
        .map(|_| {
            let mut bytes = [0; 32];
            for c in bytes.chunks_mut(8) {
                c.copy_from_slice(&rng.next_u64().to_le_bytes());
            }
            let dna = Dna(bytes);
            let song = Song::generate(dna, [None; 4]);
            let hex: String = song.encode().iter().map(|b| format!("{b:02x}")).collect();
            serde_json::json!({"dna":dna.to_string(),"sng1_hex":hex})
        })
        .collect();
    println!("{}",serde_json::to_string_pretty(&serde_json::json!({"provenance":"Local regression fixtures generated by this Rust implementation, NOT independent acceptance vectors","version":"seedsong-music/1","vectors":vectors})).unwrap());
}
